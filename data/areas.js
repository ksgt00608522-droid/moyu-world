/* 魔鱼世界 · 区域表
   全局：G.data.areas

   区域是房间的分组。一个区域里有一个「中心房间」（玩家进来第一眼看到的那个），
   其余房间都从中心出发、经过若干扇门到达。
   比如大厅区域 = 大厅 + 四扇门通向的四间屋。

   为什么要这一层：房间多起来以后，光看 doors 的指向推不出"这屋属于哪一块"，
   id 也容易撞车。有了区域，房间可以按 `区域_房间` 命名，素材也能一个区域一个文件。

   注意：赋值号右边必须是**严格的 JSON**（双引号、无尾逗号、无注释）。
   tools/validate.mjs 会剥掉前缀后用 JSON.parse 校验，写错会直接报错。

   字段：
     id      唯一标识，小写字母数字下划线，不带 room_ 前缀
     name    显示名，会出现在「地图点位状态」面板里
     center  这个区域的中心房间 id，必须是本区域里的房间
     parent  上层区域 id，可选。现在还没有嵌套区域，留着以后做子区域

   新增区域后记得回来登记，并给房间补上对应的 area 字段 ——
   validate.mjs 会因为"房间没有 area"直接报错，漏不了。 */

