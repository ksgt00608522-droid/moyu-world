/* 魔鱼世界 · NPC 表
   全局：G.data.npcTypes / G.data.attitudeStages / G.data.npcs

   注意：三个赋值号右边都必须是**严格的 JSON**（双引号、无尾逗号、无注释）。
   tools/validate.mjs 会剥掉前缀后用 JSON.parse 校验，写错会直接报错。

   ------------------------------------------------------------------
   一、类型表 G.data.npcTypes
   ------------------------------------------------------------------
   NPC 按类型上色。**加类型只改这里**，不用碰 CSS 和 JS ——
   地图渲染时会把 color 写成格子上的 --npc-color，样式规则留在 CSS 里。

     id     类型标识
     name   显示名，出现在「地图点位状态」面板里
     color  地图上那个字的颜色，同时也是那一格边框的颜色

   现在只定了几种常见的，数量还没定，随时可以加。

   ------------------------------------------------------------------
   二、态度阶段表 G.data.attitudeStages
   ------------------------------------------------------------------
   态度是 0–100 的分数，按下面的门槛切成几个阶段。
   **数组必须按 min 升序排列**，映射函数见 js/rules.js 的 attitudeStage()。

     min    这个阶段从多少分开始（含）
     name   阶段名
     color  面板里显示这个阶段名用的颜色

   现阶段态度只是展示，还没接任何玩法。

   ------------------------------------------------------------------
   三、NPC 表 G.data.npcs
   ------------------------------------------------------------------
     id        唯一标识，npc_ 前缀 + 小写字母数字下划线
     name      名字，显示给玩家
     glyph     **地图上画的那个字**。跟 name 分开定义 ——
               名字往往是两三个字，格子只放得下一个字。
     type      类型 id，决定地图上的颜色，必须在 npcTypes 里
     attitude  态度分，0–100 的整数
     talk      **普通对话台词**，非空字符串数组，每次对话随机挑一句
               （走 G.rng，读档后不会靠反复对话刷出不同结果）。
               任务对话不写在这里 —— 那是任务自己的 offer / turnin。
     at        **出现位置**，一个数组。一个 NPC 可以出现在多个房间、
               多个区域，也可以在同一个房间里出现好几处 —— 就写多条。

   at 的每一项：{ "room": 房间 id, "x": 列, "y": 行 }
   房间 id 必须在 data/rooms/*.js 里存在，坐标必须是能站的格子（不能是墙），
   而且**不能开在门格上** —— 门是通道，站个人会把路堵住。

   **NPC 挡路。** 它站的那一格过不去，玩家只能走到旁边再跟它说话
   （见 js/data.js 的 walkable 与 npcsNear）。所以：
     - NPC 不能把房间里的门堵死，validate.mjs 会从出生点做一遍可达性检查
     - 出生点也不能正好落在 NPC 身上

   NPC 身上挂什么任务**不在这里写** —— 任务自己声明 giver / room，
   见 data/quests.js 和 G.quests.ofNpc()。 */

