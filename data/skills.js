/* 魔鱼世界 · 技能表
   全局：G.data.skills

   注意：push(...) 里的内容必须是**严格的 JSON**（双引号、无尾逗号、无注释）。
   tools/validate.mjs 会剥掉前缀后按 JSON 解析校验，写错会直接报错。

   ------------------------------------------------------------------
   一、字段
   ------------------------------------------------------------------
     id        唯一标识，skl_ 前缀 + 小写字母数字下划线
     name      显示名
     kind      'passive'（被动）或 'active'（主动）
     desc      一句话描述。文字 RPG 的质感全在文案上
     mods      被动技能必填。修正项数组，见下
     applies   主动技能必填。使用后挂上的状态 id，必须在 statuses 里

   ------------------------------------------------------------------
   二、被动 vs 主动
   ------------------------------------------------------------------
   **被动技能拥有就生效**，不需要使用。它的修正算"角色固有"那一段，
   **吃生命惩罚**（见 docs/设定/04-数值与成长.md）。

   **主动技能用一次、挂一个状态**，技能本身不带修正 —— 修正在状态里。
   这么设计是为了只留一条施加路径：所有临时修正都来自状态。
   主动技能从**法术书**的「法术」标签页点格子施放（或直接 `cast 技能名`）。

   ------------------------------------------------------------------
   三、修正项 mods
   ------------------------------------------------------------------
     { "attr": "str", "add": 1 }     加值：力量 +1
     { "attr": "int", "pct": 20 }    百分比：智力 +20%

   attr 必须是 js/rules.js 属性表里的 key：
     str 力量 / int 智力 / spr 精神 / dex 灵巧 / luk 幸运 / per 感知

   add 和 pct 二选一。多个修正项**加值先相加、百分比先相加**，
   不是逐个相乘。

   ------------------------------------------------------------------
   四、技能怎么获得
   ------------------------------------------------------------------
   还没有获取途径（掉落 / 任务奖励 / 学习都没做）。
   新建角色直接带上下面这两个，用来把"修正项 → 最终属性"这条链跑通。
*/

G.data.skills.push(
  {
    "id": "skl_ironbone",
    "name": "铁骨",
    "kind": "passive",
    "desc": "筋骨结实，力气比常人大一截。",
    "mods": [ { "attr": "str", "add": 1 } ]
  },
  {
    "id": "skl_focus",
    "name": "凝神",
    "kind": "active",
    "desc": "屏息凝神片刻，脑子转得快一些。",
    "applies": "st_focus"
  }
);
