/* 魔鱼世界 · 物品表
   全局：G.data.itemKinds / G.data.moneyTypes / G.data.items

   注意：三个赋值号右边都必须是**严格的 JSON**（双引号、无尾逗号、无注释）。
   tools/validate.mjs 会剥掉前缀后用 JSON.parse 校验，写错会直接报错。

   ------------------------------------------------------------------
   一、分类表 G.data.itemKinds
   ------------------------------------------------------------------
   分类**只决定配色和排序，不决定行为** —— 跟事件点、状态一样，
   物品"能做什么"看它写了哪些字段，不看 kind 是什么：

     写了 use     详情框里出现「使用」按钮
     写了 panel   详情框里出现一个打开对应面板的按钮
     都没写       详情框里只有描述，没有按钮

   所以"清心草能吃"是因为它写了 use，不是因为它 kind 是 consumable。
   **加分类只改这张表**，不用碰 CSS 和 JS —— 跟 npcTypes / eventTypes 同一个做法。

     id     类型标识
     name   显示名
     color  背包标签和分类小标签用的颜色

   ------------------------------------------------------------------
   二、币种表 G.data.moneyTypes
   ------------------------------------------------------------------
   **货币是数字，不是物品。** 它存在存档的 wallet 字段里（币种 id -> 数量），
   **不占背包格**；钱袋只是"查看余额的入口"。

   现在只有一种。**结构留了多币种** —— 余额面板按这张表逐行画，
   以后加"银币 / 铜币"只改这里，代码一行都不用动。
   **现在不做兑换**（汇率是玩法，等真有第二种币再说）。

     id     币种标识，效果里 money 的键就是它
     name   显示名
     color  余额那一行的颜色

   ⚠️ 「金币」是**占位名** —— 命名风格在 99-待定问题.md 的 D 组还没拍板。
   等拍了改 name 就行：存档里存的是 id（coin），改名不用迁移。

   ------------------------------------------------------------------
   三、物品表 G.data.items
   ------------------------------------------------------------------
     id     唯一标识，itm_ 前缀 + 小写字母数字下划线
     name   显示名
     kind   分类 id，必须在 itemKinds 里
     desc   一句话描述
     stack  **必填**。true = 可堆叠（给几次累加几次，没有上限）
                          false = 唯一（恒为 1，已经有了再给等于没给）
     use    可选。使用效果，一串效果（跟事件点的 onUse 同形）。
             写了才能"使用"：跑一遍效果 + **数量减一**。
     panel  可选。能打开哪个面板：'wallet'（钱袋）/ 'notebook'（笔记本）。
             **不消耗** —— 钱袋点开看看，袋子还在。

   **use 和 panel 不能同时写** —— 两个都会往详情框里塞一个按钮，
   一个物品只该有一个动作。validate.mjs 直接拦。

   **没有 glyph。** 物品不出现在地图上，背包里画的是名字。

   ------------------------------------------------------------------
   四、效果键（use 里能写什么）
   ------------------------------------------------------------------
   跟事件点共用一套，由 js/effects.js 解释：
     { "log": "…", "cls": "ok" }        往记事里写一行
     { "buff": "st_focus" }             挂一个状态
     { "money": { "coin": "+20" } }     改货币（值是带符号的字符串）
     { "give": { "itm_x": 1 } }         给物品
     { "take": { "itm_x": 1 } }         取走物品
     { "set": { "player.hp": "+20" } }  改数值（**现在还是空壳**）

   ⚠️ **set 现在不真改数值**（玩法还没定，见 10-事件点.md）。
   所以现在想让一个物品"有效果"，就挂状态 —— 写 set 只是记在案上。

   ------------------------------------------------------------------
   五、现在有哪几个
   ------------------------------------------------------------------
     itm_purse   钱袋     特殊 · 唯一 · panel:wallet    由 ev_purse 给
     itm_note    笔记本   特殊 · 唯一 · panel:notebook  由 ev_note 给
     itm_herb    清心草   消耗品 · 可堆叠 · use:凝神     由 ev_herb 反复采

   钱袋和笔记本**开局都不带，全靠捡** —— 没捡到就看不到余额 / 任务清单，
   这是设计内的（见 06-物品与技能.md 的「货币」）。

   itm_herb 是唯一一个演示 use 的素材（也是唯一可堆叠的）：
   采草 -> 攒够三株 -> 交任务 q_herb -> 拿钱，正好把整条路走一遍。 */

