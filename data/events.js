/* 魔鱼世界 · 事件点表
   全局：G.data.eventTypes / G.data.events

   注意：两个赋值号右边都必须是**严格的 JSON**（双引号、无尾逗号、无注释）。
   tools/validate.mjs 会剥掉前缀后用 JSON.parse 校验，写错会直接报错。

   ------------------------------------------------------------------
   一、类型表 G.data.eventTypes
   ------------------------------------------------------------------
   事件点按类型上色，并且**类型给出默认的"藏不藏"和"用完走不走"**。
   **加类型只改这里**，不用碰 CSS 和 JS —— 地图渲染时会把 color 写成
   格子上的 --event-color，样式规则留在 CSS 里。

     id      类型标识
     name    显示名，出现在「地图点位状态」面板里
     color   地图上那个字的颜色，同时也是那一格边框的颜色
     hidden  可选，默认 false。true = 触发之前不画字，只画一个空框
     once    可选，默认 false。true = 用一次就没了

   数量还没定，随时可以加。

   ------------------------------------------------------------------
   二、事件点表 G.data.events
   ------------------------------------------------------------------
     id          唯一标识，ev_ 前缀 + 小写字母数字下划线
     type        类型 id，决定颜色和默认的 hidden / once，必须在 eventTypes 里
     name        名字，显示给玩家
     glyph       **地图上画的那个字**。跟 name 分开定义 ——
                 名字往往两三个字，格子只放得下一个字。
     at          **出现位置**，一个数组，跟 NPC 的 at 完全同形。
                 一个事件点可以出现在多个房间、多个区域，也可以在同一个
                 房间里出现好几处 —— 就写多条。**同一个 id = 同一份状态**：
                 在一处用掉了，别处的也没了。
     desc        可选。站在上面时的一句描述
     hint        可选。**按钮上写什么字**（"喝一口" / "捡起来"）。
                 不填用通用文案
     onCollide   可选。走上去**自动**触发时的一串效果
     onUse       可选。站上去**点按钮**触发时的一串效果
     once        可选。覆盖类型表的 once
     hidden      可选。覆盖类型表的 hidden

   **onCollide 和 onUse 至少要写一个**，两个都没有的事件点什么也做不了，
   validate.mjs 直接报错。

   **没有任何"类型"字段能决定它怎么触发** —— 触发方式完全由"写了哪个回调"
   决定。三个维度互相正交，随便组合（见 docs/设定/10-事件点.md 第二节）：
     怎么触发  onCollide / onUse / 两个都写
     去留      once
     藏不藏    hidden
   不要把它们写成一个"泉水型 / 物品型 / 机关型"的枚举 ——
   那样以后想加"踩了会响、还能再点一下"的组合就得改代码。

   ------------------------------------------------------------------
   三、at 的四条约束（跟 NPC 不一样，别抄错）
   ------------------------------------------------------------------
   房间必须存在，坐标必须在图内，而且：
     - **不能在墙里** —— 走不上去的东西没有意义
     - **不能在门格上** —— 门格上的动作是"进入"，再挂一个事件点两个按钮会打架
     - **不能在出生点上** —— 否则玩家一睁眼就站在上面
     - **不能在 NPC 那一格上** —— NPC 挡路，那一格玩家永远走不上去
     - 同一个房间里同一格不能有两个事件点

   **事件点不挡路。** 这是它跟 NPC 最本质的区别 —— G.data.walkable()
   不算事件点，玩家必须能走上去（见 docs/设定/10-事件点.md 第一节）。

   ------------------------------------------------------------------
   四、效果（effects）
   ------------------------------------------------------------------
   onCollide / onUse 各自是一个数组，每项是一条小效果，按顺序执行。
   这套键由 js/effects.js 解释，**物品的 use 用的是同一套**：

     { "log": "…", "cls": "ok" }              往记事里写一行
     { "give": { "itm_x": 1 } }               给物品
     { "take": { "itm_x": 1 } }               取走物品
     { "money": { "coin": "+12" } }           改货币（值是带符号的字符串）
     { "buff": "st_focus" }                   挂一个状态
     { "set": { "player.hp": "-5" } }         数值改动（**现在不真改**）

   cls 取值跟 G.ui.log() 的第二参数一样：title / info / sys / ok / warn / err。
   不填按 info。

   一条效果里可以同时有多个键（"写一行 + 真的加钱"）。
   打错一个字母就等于这条效果静默失效，validate.mjs 会拦下。

   give / take 的值是**正整数**（数量），键必须是真实物品；
   唯一物品（stack: false）不许写大于 1。
   money 的键是币种 id，值是**带符号的字符串**（跟 set 一个规矩）——
   货币不是物品、不占背包格，所以单独一个键，不混进 give / take。
   buff 的值是状态 id，已经挂着就是续期。

   ⚠️ **只有 set 现在不真改数值。** G.rules.applyEffect 是个空壳，
   因为玩法还没定（终点 / 时长 / 战斗 / 死亡处理全在 99-待定问题.md 的 A 组，
   连"有没有血量"都还没定）。素材照写、照校验、照解析，就是不生效。
   等玩法定了，只改 applyEffect 那一个函数，素材一行都不用动。

   ⚠️ **而且现在一条 set 都没写** —— 因为**没有合法的目标字段**：
   04-数值与成长.md 定了"生命 / 灵性只做显示，只有状态的 tick 能改它们"，
   六项基础属性和神性则是角色自己的东西，事件点不该直接去改。
   解析和校验这两条路**留着别删**（见 10-事件点.md），
   等 A 组拍板、真有了能改的字段，素材直接写上就生效。

   **give / take / money / buff 不受这条影响** —— 那四条都已经接通了。

   ------------------------------------------------------------------
   五、状态存在哪
   ------------------------------------------------------------------
   存档的 events 字段：事件点 id -> { times }（触发 / 互动过几次）。
   **只记次数，不记布尔** —— 一个 times 同时能回答：
     once 的"用掉了没有"  → times > 0
     hidden 的"揭开没有"  → times > 0
     可重复的"踩过几回了" → times 本身
   **"没有记录" = 一次都没触发过**，所以旧存档不用迁移就能直接用。 */

